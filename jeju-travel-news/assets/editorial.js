export function curateArticles(articles = []) {
  const articlesBySlug = new Map(articles.map((article) => [article.slug, article]));
  return curatedSlugs
    .map((slug) => {
      const article = articlesBySlug.get(slug);
      const override = editorialOverrides[slug];
      if (!article || !override) return null;
      const content = override.editorialSections.flatMap((section) => section.paragraphs);
      return {
        ...article,
        ...override,
        content,
        status: "published",
        author: editorialProfile.author,
        publisher: editorialProfile.publisher,
        reviewedAt: editorialProfile.reviewedAt,
        dateModified: editorialProfile.reviewedAt,
        reviewMethod: editorialProfile.reviewMethod
      };
    })
    .filter(Boolean);
}
